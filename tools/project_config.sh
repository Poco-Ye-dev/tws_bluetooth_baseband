#!/usr/bin/env bash
#
# Select the CPU and application, then rebuild.
#
#   project_config.sh <cpu> <app>
#
# The values are written to config.mk so plain `make` picks them up.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG="$ROOT/config.mk"

usage() {
    echo "usage: $0 <cpu> <app>" >&2
    echo "  cpu: tcl23321 tcl34311 tcl44808 tcl52747 tcl64729 tcl76484 tcl77334" >&2
    echo "  app: earphone soundbox dongle iot" >&2
    exit 1
}

[ $# -eq 2 ] || usage

cpu="$1"
app="$2"

[ -f "$ROOT/make/platform/$cpu.mk" ] || {
    echo "unknown cpu: $cpu" >&2
    usage
}
[ -f "$ROOT/apps/$app/Makefile" ] || {
    echo "unknown app: $app" >&2
    usage
}

tmp="$(mktemp "$ROOT/tmp/config.XXXXXX")"
{
    echo "# Generated by tools/project_config.sh"
    echo "CPU := $cpu"
    echo "APP_CASE := $app"
} > "$tmp"
mv "$tmp" "$CONFIG"

echo "target: cpu=$cpu app=$app"
